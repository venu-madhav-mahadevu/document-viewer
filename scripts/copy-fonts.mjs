// Free fonts with the same letter widths as the common Office fonts, so documents wrap on
// the same lines as in Word / PowerPoint on devices that don't have the Office fonts
// (phones, Linux). Each is registered under the Office name with local() first, so a
// device that has the real font still uses it.
//   Calibri -> Carlito, Cambria -> Caladea, Arial -> Arimo, Times New Roman -> Tinos, Courier New -> Cousine
// Output: public/fonts/office-fonts.css + woff2 files (OFL-1.1, from @fontsource).
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dest = join(root, 'public', 'fonts');
const FONTS = [
  ['carlito', ['Calibri', 'Calibri Light']],
  ['caladea', ['Cambria']],
  ['arimo', ['Arial', 'Helvetica']],
  ['tinos', ['Times New Roman', 'Times']],
  ['cousine', ['Courier New', 'Courier']],
];

if (existsSync(dest)) rmSync(dest, { recursive: true });
mkdirSync(dest, { recursive: true });
let css = '/* Generated by scripts/copy-fonts.mjs: metric-compatible fallbacks for Office fonts (OFL-1.1). */\n';
let files = 0;
for (const [pkg, officeNames] of FONTS) {
  const dir = join(root, 'node_modules', '@fontsource', pkg);
  if (!existsSync(dir)) { console.log(`@fontsource/${pkg} not installed; skipped`); continue; }
  for (const variant of ['400', '400-italic', '700', '700-italic']) {
    const source = readFileSync(join(dir, `${variant}.css`), 'utf8');
    for (const block of source.match(/@font-face\s*{[^}]*}/g) || []) {
      const file = /url\(\.\/files\/([^)]+\.woff2)\)/.exec(block)?.[1];
      if (!file) continue;
      copyFileSync(join(dir, 'files', file), join(dest, file));
      files++;
      for (const office of officeNames) {
        const face = block
          .replace(/font-family:\s*'[^']+'/, `font-family: '${office}'`)
          .replace(/src:[^;]+;/, `src: local('${office}'), url(./${file}) format('woff2');`);
        css += `${face}\n`;
      }
    }
  }
}
writeFileSync(join(dest, 'office-fonts.css'), css);
console.log(`office fonts copied to public/fonts (${files} files)`);
